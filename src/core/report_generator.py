def _t(lang: str, key: str) -> str:
    return _TEXTS.get(lang, _TEXTS["zh"]).get(key, _TEXTS["zh"].get(key, key))


def generate_report(
    disaster_id: str,
    stats: Dict[str, Any],
    source_layer: str = "",
    boundary_layer: str = "",
    lang: str = "zh",
    user_text: str = "",
    threshold: float = WARNING_THRESHOLD,
) -> Dict[str, Any]:
    """根据覆盖率统计生成三语 Markdown 风险评估报告。

    Parameters
    ----------
    disaster_id : str
        灾种注册 ID（earthquake/flood/landslide/wildfire）。
    stats : dict
        coverage_analysis 返回的统计：source_count / radius_m /
        total_area / covered_area / coverage_rate。
    source_layer / boundary_layer : str
        参与分析的图层名（缺省显示为 "-"）。
    lang : str
        zh / ja / en。
    user_text : str
        触发本次分析的用户指令（可为空）。
    threshold : float
        覆盖率预警阈值（百分比）。

    Returns
    -------
    dict
        {"success": bool, "report_path": str, "warning": str,
         "disaster_name": str, "coverage_rate": float}
        warning 为空表示未触发预警。
    """
    from core.disaster_registry import get_disaster, get_disaster_name, get_risk_zone_layer

    info = get_disaster(disaster_id) or {}
    disaster_name = get_disaster_name(disaster_id, lang)
    if not stats or "coverage_rate" not in stats:
        return {
            "success": False,
            "report_path": "",
            "warning": "",
            "disaster_name": disaster_name,
            "coverage_rate": None,
        }

    coverage_rate = float(stats["coverage_rate"])
    rate_display = f"{coverage_rate:.4f}"
    # 覆盖率 < 阈值（默认 50%）时预警
    warning_msg = ""
    if coverage_rate < threshold:
        warning_msg = _t(lang, "warning_msg").format(
            disaster=disaster_name,
            rate=f"{coverage_rate:.2f}",
            threshold=f"{threshold:.2f}",
        )

    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    os.makedirs(REPORTS_DIR, exist_ok=True)
    report_path = os.path.join(REPORTS_DIR, f"risk_report_{stamp}_{disaster_id}.md")

    src = source_layer or "-"
    bnd = boundary_layer or get_risk_zone_layer(disaster_id) or "-"
    radius = stats.get("radius_m", "-")
    total_area = stats.get("total_area", "-")
    covered_area = stats.get("covered_area", "-")
    source_count = stats.get("source_count", "-")

    lines: list[str] = []
    lines.append(f"# {_t(lang, 'title')}")
    lines.append("")
    lines.append(f"- **{_t(lang, 'generated_at')}**: {ts}")
    lines.append(f"- **{_t(lang, 'disaster')}**: {disaster_name} (`{disaster_id}`)")
    lines.append(f"- **{_t(lang, 'source_layer')}**: {src}")
    lines.append(f"- **{_t(lang, 'boundary_layer')}**: {bnd}")
    if user_text:
        lines.append(f"- **{_t(lang, 'user_text')}**: {user_text}")
    lines.append("")
    lines.append(f"## {_t(lang, 'stats')}")
    lines.append("")
    lines.append(f"| {_t(lang, 'source_count')} | {_t(lang, 'radius_m')} | {_t(lang, 'total_area')} | {_t(lang, 'covered_area')} | {_t(lang, 'coverage_rate')} |")
    lines.append("| --- | --- | --- | --- | --- |")
    lines.append(f"| {source_count} | {radius} | {total_area} | {covered_area} | **{rate_display}%** |")
    lines.append("")
    if warning_msg:
        lines.append(f"## {_t(lang, 'warning_title')}")
        lines.append("")
        lines.append(f"> ⚠️ {warning_msg}")
        lines.append("")
    lines.append(f"### {_t(lang, 'note')}")
    lines.append("")
    lines.append(_t(lang, "note_text"))
    lines.append("")

    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    return {
        "success": True,
        "report_path": report_path,
        "warning": warning_msg,
        "disaster_name": disaster_name,
        "coverage_rate": coverage_rate,
    }
