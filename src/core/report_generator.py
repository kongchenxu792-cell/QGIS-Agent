_PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
REPORTS_DIR = os.path.join(_PROJECT_ROOT, "user_data", "reports")

# 覆盖率预警阈值（百分比）：低于该值触发预警
WARNING_THRESHOLD = 50.0

